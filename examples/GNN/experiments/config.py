"""Experiment matrix and thresholds for the GNN verification campaign.

Compares n2v GraphStar verification (reach / verify / falsify / k-hop subgraph)
against the MATLAB GNNV (NNV) reference across IEEE bus sizes and GNN types,
logging verification verdicts and timing.
"""

from pathlib import Path

GNNV_OUTPUTS = Path("/home/verivital/Anne/graph_verification/gnnv2/gnn_training/outputs")
HERE = Path(__file__).resolve().parent
RESULTS = HERE / "results"
REFS = RESULTS / "refs"

# (label, n_nodes) — full 3x3 PF matrix
BUSES = [("ieee24", 24), ("ieee39", 39), ("ieee118", 118)]
TYPES = ["gcn", "sage", "gine_pretrain"]
TASK = "pf"

EPS_VALUES = [1e-3, 1e-2]        # L_inf radius on input node features
INSTANCES = [0, 1, 2]           # test-instance indices (0-based)
DELTA = 0.10                     # robustness band on outputs: nominal +/- DELTA
SUBGRAPH_TARGETS = [0, 1, 2]    # node indices verified via k-hop subgraph

# Full-graph get_ranges is one LP per output and is intractable at large N;
# above this node count we report reach() timing + per-target subgraph verdicts
# instead of a full-graph bound box.
FULL_GETRANGES_MAX_NODES = 45

# GINE's two ReLUs per layer pack the predicate polytope with constraints, so
# full-graph get_ranges is intractable beyond ieee24 (measured: ieee39/GINE
# full-graph bound extraction does not finish, while ieee39/GCN-SAGE do in <1s).
# Above this node count GINE uses the per-target subgraph path.
GINE_FULL_MAX_NODES = 24

# Cross-tool reference is generated by MATLAB only where full-graph getRanges is
# tractable in both tools.
REFERENCE_BUSES = ["ieee24", "ieee39"]

# Discrepancy triggers -> pause-and-report.
PARITY_TOL = 1e-4                # |n2v_forward - pytorch_pred|
SOUNDNESS_TOL = 1e-6            # n2v box must contain MATLAB box within this


def checkpoint(bus: str, typ: str, task: str = TASK) -> Path:
    return GNNV_OUTPUTS / f"{bus}_{task}" / f"{typ}_{task}_{bus}.mat"


def ref_path(bus: str, typ: str, task: str = TASK) -> Path:
    return REFS / f"{typ}_{task}_{bus}_reference.mat"
